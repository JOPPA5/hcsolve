im0 = Image.open(sys.argv[1]); out=sys.argv[2]
specs = {"t1":(25,32,540,56),"t2":(25,54,540,78),"t3":(25,75,250,175),
"b1":(25,258,235,322),"b2":(225,258,445,322),"b3":(25,318,235,382),"b4":(225,318,445,382),
"b5":(25,378,235,442),"b6":(225,378,445,442),"b7":(25,438,235,502),"b8":(225,438,445,502),
"b9":(25,498,235,560),"b10":(225,498,445,560),"b11":(25,555,235,600),"b12":(225,555,445,600)}
for k,(a,b,c,d) in specs.items():
    im=im0.crop((a,b,c,d)); s=4
    im.resize((im.width*s,im.height*s),Image.LANCZOS).save(f"{out}/{k}.png")
