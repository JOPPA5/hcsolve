from PIL import Image
import glob,sys
im=Image.open(glob.glob('hires/*adr.jpg')[0]).convert('RGB')
S=2.1675
R={'a1':(20,15,420,115),'a2':(320,15,700,115),'a3':(20,105,420,205),'a4':(320,105,700,205),
'a5':(20,195,420,300),'a6':(320,195,700,300),
'b1':(20,300,420,410),'b2':(350,300,760,430),'b3':(20,400,420,510),'b4':(350,400,700,510),'b5':(20,500,420,610),'b6':(350,500,700,610),'b7':(20,600,420,710),'b8':(350,600,720,710),
'c1':(20,730,420,840),'c2':(320,730,700,860),'c3':(20,800,420,900),'c4':(320,800,710,910),'c5':(20,890,700,975),
'd1':(690,20,1000,125),'d2':(950,20,1290,125),'d3':(690,100,1000,220),'d4':(950,100,1290,220)}
for k,(a,b,c,d) in R.items():
    c0=im.crop((int(a*S),int(b*S),int(c*S),int(d*S)))
    c0=c0.resize((c0.width*2,c0.height*2),Image.LANCZOS)
    c0.save('crops/%s.png'%k)
